def build_all_posts():
    footer = f"\n\n🔗 کانال گیاهان دارویی ارسباران:\n{CHANNEL_LINK}"
    posts = []
    for herb in HERBS:
        for fact in herb["f"]:
            for how in herb["h"]:
                for intro in INTROS:
                    for ctx in CONTEXTS:
                        posts.append(
                            f"{herb['e']} {herb['n']}\n\n{intro}\n\n{ctx}: {herb['n']} {fact}\n\n✅ {how}{footer}"
                        )
    posts = list(dict.fromkeys(posts))
    posts.sort(key=lambda t: hashlib.md5(t.encode()).hexdigest())
    return posts

def load_state():
    if STATE_FILE.exists():
        with open(STATE_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return {"used": [], "cycle": 1}

def save_state(state):
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, ensure_ascii=False, indent=2)

def pick_post(posts, state):
    used = set(state.get("used", []))
    available = [(hashlib.md5(p.encode()).hexdigest()[:16], p) for p in posts if hashlib.md5(p.encode()).hexdigest()[:16] not in used]
    if not available:
        state["used"] = []
        state["cycle"] = state.get("cycle", 1) + 1
        available = [(hashlib.md5(p.encode()).hexdigest()[:16], p) for p in posts]
        print(f"♻️ دوره جدید: cycle={state['cycle']}")
    key, post = random.choice(available)
    return key, post, state

def is_within_posting_hours():
    now = datetime.now(ZoneInfo("Asia/Tehran"))
    return 8 <= now.hour <= 23

def send_message(text):
    url = f"https://botapi.rubika.ir/v3/{TOKEN}/sendMessage"
    r = requests.post(url, json={"chat_id": CHAT_ID, "text": text}, timeout=30)
    return r.json()

def main():
    if not TOKEN:
        print("❌ BOT_TOKEN نیست")
        return
    if not is_within_posting_hours():
        print("⏰ خارج از ساعت ۸ تا ۲۳")
        return
    posts = build_all_posts()
    state = load_state()
    key, post, state = pick_post(posts, state)
    print(f"کل پست یکتا: {len(posts)} | ارسال‌شده این دوره: {len(state.get('used', []))} | دوره: {state.get('cycle', 1)}")
    print(post[:120], "...")
    result = send_message(post)
    print("API:", result)
    if isinstance(result, dict) and result.get("status") == "OK":
        state.setdefault("used", []).append(key)
        save_state(state)
        print(f"✅ باقی‌مانده این دوره: {len(posts) - len(state['used'])}")
    else:
        print("⚠️ ارسال نشد؛ state عوض نشد")

if __name__ == "__main__":
    main()
